def _mark_price(token):
    """Текущая цена токена для отметки «мы здесь» на карте. -> float | None.

    НЕОБЯЗАТЕЛЬНА И БЕРЁТСЯ ФАКТОМ. Приходит не из Nansen, а с Hyperliquid, поэтому её сбой
    не имеет права рушить карту: без неё карта остаётся честной картой уровней, просто без
    отметки. Выдуманная цена дала бы отметку «осталось 3%», которой никто не мерил.
    """
    try:
        import asyncio
        import oc_perps as _hl
        _p = os.path.join(ROOT, 'onchain')
        if _p not in sys.path:
            sys.path.insert(0, _p)
        st = asyncio.run(_hl.hl_coin_stats(token))
        return (st or {}).get('mark') or None
    except Exception as e:                        # noqa: BLE001
        print('[nansen_gate] цена для карты не взялась: %s' % str(e)[:100])
        return None


def feed(limit=40):
    """ПОТОК ВЫЗОВОВ: последние строки телеметрии для экрана «доказательство живости».
    -> {'rows': [...], 'totals': {...}}.

    ЗАЧЕМ ЭТОТ ЭКРАН ВООБЩЕ. Правила конкурса требуют ЖИВЫЕ данные в кадре. Телеметрия уже
    пишет одну строку на вызов, поэтому доказательство достаётся бесплатно: видно время,
    эндпоинт, класс исхода, миллисекунды, кредиты, кэш/сеть и поверхность.

    ЧЕГО ЗДЕСЬ НЕТ: идентификаторов людей. В строке лога человек лежит суточным хешем (`u`),
    и наружу он не уезжает - ни в этот экран, ни в выгрузку. Публичный поток вызовов с
    опознаваемыми людьми был бы худшим видом «доказательства».
    """
    import nansen_log as T
    rows = T.read_day(T._day()) or []
    out = []
    for r in rows[-int(limit):]:
        out.append({
            'ts': T._i(r, 'ts'),
            'ep': r.get('ep') or '?',
            'scene': r.get('scene') or '?',
            'out': r.get('out') or '?',
            'ms': T._i(r, 'ms'),
            'cr': T._i(r, 'cr'),
            'cache': 1 if str(r.get('cache')) in ('1', 'True') else 0,
            'surface': r.get('srf') or T.DEFAULT_SURFACE,
        })
    _calls = len(rows)
    _cache = sum(1 for r in rows if str(r.get('cache')) in ('1', 'True'))
    return {'rows': out,
            'totals': {'calls': _calls,
                       'credits': sum(T._i(r, 'cr') for r in rows),
                       'cache_hits': _cache,
                       'cache_share': (round(100.0 * _cache / _calls) if _calls else 0),
                       'day': T._day()},
            'now': int(time.time())}
