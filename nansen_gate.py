# -*- coding: utf-8 -*-
"""nansen_gate.py — ШЛЮЗ МИНИ-АППА К СЦЕНАМ NANSEN. Экран просит, бот считает, браузер рисует.

ГДЕ ЭТОТ МОДУЛЬ СТОИТ В АРХИТЕКТУРЕ, И ПОЧЕМУ ИМЕННО ТАК

У бота НЕТ входящего порта - он опрашивает почтовый ящик Cloudflare Worker'а
(`worker_bridge`: `GET /pull` → работа → `POST /done`). Поэтому «маршрут `GET /nansen/<сцена>`»
физически невозможен в том виде, в каком его просят на словах: ключ Nansen, лимиты человека и
телеметрия живут В БОТЕ, а Worker до бота не достаёт. Свой маршрут на Воркере смог бы ответить
только из своей базы - то есть завёл бы ВТОРОЙ источник чисел и нарушил Закон 0 на первом же
экране. Поэтому шлюз - это вид сигнала `nsn` в существующем ящике, и здесь его содержательная
половина.

ЧТО ЭТОТ МОДУЛЬ ДЕЛАЕТ, ПО ПОРЯДКУ
  1. разбирает просьбу экрана (имя сцены + параметры) и отказывает ПО ФОРМЕ до любой сети;
  2. проверяет лимиты ТЕМИ ЖЕ функциями, что бот (`nansen_limits`), и знает цену предстоящего
     вопроса до того, как его задать;
  3. открывает сцену телеметрии с `surface='miniapp'` - НЕ новую сцену, а новую ПОВЕРХНОСТЬ
     старой, иначе расход по сценам перестал бы складываться;
  4. зовёт `nansen_scene.scene_data` - тот самый словарь, из которого бот строит текст;
  5. ВЫЧИЩАЕТ то, чему нельзя уезжать в браузер (полные адреса кошельков), и отдаёт конверт.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ, И ЭТО НАМЕРЕННО
  * НЕ проверяет подпись Telegram. Её проверяет Worker (`checkInitData`) ДО того, как работа
    попадёт в ящик. Вторая реализация HMAC разошлась бы с первой молча - тот же закон №40,
    по которому у нас одна дверь на команду и кнопку.
  * НЕ знает про HTTP, статусы и CORS: это слой Worker'а.
  * НЕ выводит торговые ручки. `trade/prepare` и `trade/execute` недостижимы через шлюз, и
    недостижимы ОТСУТСТВИЕМ, а не проверкой: их нет в списке сцен вовсе. Запрос такой сцены
    получает тот же отказ «неизвестный экран», что и опечатка, - шлюз не подтверждает, что
    такая ручка существует.

КЛЮЧ NANSEN НЕ ПОКИДАЕТ СЕРВЕР. Браузер видит только конверт: числа, подписи, причину отказа.
"""

import os
import sys
import time

ROOT = os.path.dirname(os.path.abspath(__file__))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

#: КАТАЛОГ ЗАПИСАННЫХ ОТВЕТОВ ДЛЯ РЕЖИМА РЕПЕТИЦИИ. Лежит рядом с ботом и НЕ уезжает в
#: публичную выжимку, если в нём остались адреса: фикстуры проходят скруббер отдельно.
FIXTURE_DIR = os.path.join(ROOT, 'nansen', 'fixtures')

#: ЦЕНА ЭКРАНА ДЛЯ ПРЕДВАРИТЕЛЬНОЙ ПРОВЕРКИ ЛИМИТА. Структурные экраны стоят единицы кредитов
#: и лимитом не ограничены (ограничен только агент), но кап по кредитам за сутки обязан ЗНАТЬ
#: цену предстоящего вопроса: пускать экран за 30, когда до капа осталось 10, значит перейти
#: его молча. Числа консервативные - лучше отказать зря, чем перейти кап незаметно.
#: Сравнительные экраны дороже одиночных РОВНО потому, что сравнивают: `sharp_markets` это
#: 1 + N + N×H запросов (при 4 рынках по 3 держателя - 17), `perp_risk` - по запросу на токен.
#: Числа консервативные вверх: недопустить дорогой экран у края капа дешевле, чем перейти кап.
SCENE_COST = {'pm_markets': 5, 'pm_reputation': 30, 'liq_map': 5, 'smart_trades': 5,
              'sharp_markets': 120, 'perp_risk': 20,
              # ТРИ НОВЫХ ЭКРАНА - ОДИН ЗАПРОС КАЖДЫЙ, и цена их в официальном списке не
              # названа вовсе. Пятёрка здесь - консервативная оценка ДЛЯ ПРОВЕРКИ КАПА, а не
              # утверждение о цене: человеку в подвале экрана честно печатается число ЗАПРОСОВ,
              # потому что придуманные кредиты в самом проверяемом месте экрана были бы ложью.
              'smart_dca': 5, 'chain_rank': 5, 'pm_positions': 5}


def _admins():
    """Кому лимиты не считаются. -> tuple.

    ЧИТАЕМ ADMIN_IDS ТЕМ ЖЕ СПОСОБОМ, ЧТО ОСТАЛЬНОЙ БОТ, и не заводим свой список: второй
    список владельцев однажды разъедется с первым, и разъезд будет виден по тому, что кто-то
    из владельцев не может открыть свой же экран (разбор в `oc_dm._admin_ids`).
    """
    out = set()
    for _x in (os.getenv('ADMIN_IDS') or '').replace(' ', '').split(','):
        if _x:
            try:
                out.add(int(_x))
            except ValueError:
                pass
    return tuple(out)


def _strip_private(env):
    """УБРАТЬ ИЗ КОНВЕРТА ТО, ЧЕМУ НЕЛЬЗЯ В БРАУЗЕР. -> тот же конверт (меняется на месте).

    ПОЛНЫЙ АДРЕС КОШЕЛЬКА - ИМЕННО ТАКОЙ СЛУЧАЙ. Бот показывает метку либо обрезанный адрес
    (`0xbbbb…0002`), и экран обязан показывать РОВНО столько же: полный адрес в JSON уехал бы
    в devtools, в скриншот и в запись экрана, а вернуть его оттуда нельзя. Обрезанная форма
    уже посчитана ботом и лежит в поле `who` - её и отдаём.

    ЭТО НЕ КОСМЕТИКА: hero-экран показывают в ролике конкурса, и кадр с чужими адресами
    нарушает то же правило, по которому у нас в выгрузке телеметрии нет идентификаторов людей.
    """
    p = (env or {}).get('payload')
    if not isinstance(p, dict):
        return env
    if isinstance(p.get('holders'), list):
        for h in p['holders']:
            if isinstance(h, dict):
                h.pop('addr', None)
    # АДРЕС КОНТРАКТА ТОКЕНА - НЕ ПЕРСОНАЛЬНЫЕ ДАННЫЕ (бот сам строит по нему ссылку, и он
    # есть в публичных документах). Но экран его НЕ РИСУЕТ, а значит и отправлять его незачем:
    # «не посылай того, чего не показываешь» дешевле, чем послабление в скруббере. Строгое
    # правило «в конверте нет адресов в форме 0x…40» стоит больше, чем поле, которое никто не
    # читает, - и именно оно поймало этот случай при записи фикстуры.
    if isinstance(p.get('rows'), list):
        for r in p['rows']:
            if isinstance(r, dict):
                r.pop('addr', None)
    # `first_row` - СЫРАЯ СТРОКА ОТВЕТА ПЛОЩАДКИ, она лежит в словаре ради диагностики
    # расхождения схемы (`schema_gap_note`) и содержит ВСЕ поля, которые прислал Nansen.
    # Экрану она не нужна, а уехать наружу может что угодно из будущих полей ответа - включая
    # то, чего сегодня там нет. Поймано скруббером при записи фикстуры на адресе контракта.
    p.pop('first_row', None)
    return env


def _scene_ctx(scene, uid):
    """Сцена телеметрии ЛИТЕРАЛЬНЫМ ИМЕНЕМ, а не переменной. -> контекстный менеджер.

    ПОЧЕМУ ТАК УРОДЛИВО, А НЕ `T.scene(scene, uid, ...)`. Реестр сцен закрыт, и его сторожит
    тест, который сверяет КАЖДЫЙ вызов `scene(...)` в репозитории со списком - по AST. Имя,
    собранное в рантайме, он сверить не может и потому считает нарушением, и он прав: сцена
    из переменной это ровно та щель, через которую в сводку попадает строка «? 5 кр» - расход
    виден, а ЧЕЙ он, нет. Этот дефект в проекте уже случался (забытая тройка имён 15.09).

    Здесь имя приходит из подписанного сигнала, то есть снаружи, поэтому развилка на литералы
    - не формальность: она ДОКАЗЫВАЕТ, что в телеметрию попадёт одно из трёх имён реестра, что
    бы ни прислал клиент. Список сцен всё равно один (`nansen_scene.SCENES`), и вход сюда
    открыт только после проверки по нему.
    """
    T = _T()
    if scene == 'pm_markets':
        return T.scene('pm_markets', uid, surface='miniapp')
    if scene == 'pm_reputation':
        return T.scene('pm_reputation', uid, surface='miniapp')
    if scene == 'liq_map':
        return T.scene('liq_map', uid, surface='miniapp')
    if scene == 'sharp_markets':
        return T.scene('sharp_markets', uid, surface='miniapp')
    if scene == 'perp_risk':
        return T.scene('perp_risk', uid, surface='miniapp')
    if scene == 'smart_dca':
        return T.scene('smart_dca', uid, surface='miniapp')
    if scene == 'chain_rank':
        return T.scene('chain_rank', uid, surface='miniapp')
    if scene == 'pm_positions':
        return T.scene('pm_positions', uid, surface='miniapp')
    return T.scene('smart_trades', uid, surface='miniapp')


def _T():
    import nansen_log as T
    return T


def _fixture_path(scene):
    return os.path.join(FIXTURE_DIR, '%s.json' % str(scene or '')[:40])


def _rehearsal(scene, lang):
    """Записанный ответ вместо живого. -> конверт с несводимой пометкой.

    ЗАЧЕМ РЕЖИМ РЕПЕТИЦИИ. Ren должен пройти маршрут пальцем несколько раз перед записью, не
    сжигая кредиты и не рискуя отказом провайдера в кадре.

    ПОМЕТКА НЕСВОДИМА НАРОЧНО: `rehearsal: true` и время записи едут В ОТВЕТЕ, а не во флаге
    на странице. Экран не может их спрятать, не правя код, и поэтому дубль с плашкой видно
    сразу - а в финальной записи репетиция запрещена.
    """
    import json
    p = _fixture_path(scene)
    try:
        with open(p, encoding='utf-8') as fh:
            env = json.load(fh)
    except Exception as e:                        # noqa: BLE001
        return {'scene': scene, 'outcome': 'badreq', 'source': 'Nansen',
                'freshness_seconds': None, 'cost_requests': 0, 'cost_credits': 0,
                'caveats': [], 'payload': None, 'lang': lang, 'rehearsal': True,
                'refusal': ('Rehearsal fixture is missing: %s' % os.path.basename(p))
                if lang == 'en' else
                ('Записанного ответа нет: %s' % os.path.basename(p)),
                'why': str(e)[:120]}
    env['rehearsal'] = True
    env.setdefault('recorded_at', None)
    # НИ ОДНОГО ВЫЗОВА К NANSEN И НИ ОДНОЙ СТРОКИ ТЕЛЕМЕТРИИ: репетиция не имеет права
    # выглядеть в отчётах как живой прогон, иначе доказательство живости перестанет быть
    # доказательством.
    return _strip_private(env)


def handle(req, uid, lang='ru', bot_un=None):
    """ЕДИНАЯ ДВЕРЬ ШЛЮЗА. -> конверт (dict), всегда непустой.

    `req` - разобранные Worker'ом поля сигнала: {'sc': сцена, 'mk': рынок, 'tk': тикер,
    'lg': язык, 'rh': репетиция}. Форма уже проверена белым списком на Воркере; здесь
    проверяется СМЫСЛ (есть ли такая сцена, хватает ли лимита).

    Отказ ВСЕГДА с причиной и ВСЕГДА из того же канала, что у бота: экран рисует состояние,
    а не пустой график. Шесть нулевых столбиков выглядят как измерение и врут сильнее, чем
    отсутствие картинки.
    """
    import nansen_scene as S
    req = req or {}
    scene = str(req.get('sc') or '')[:40]
    lg = 'en' if (req.get('lg') or lang) == 'en' else 'ru'

    # ── 1. ФОРМА: неизвестная сцена - отказ ДО любой сети и без подтверждения существования
    if scene not in S.SCENES:
        return {'scene': scene, 'outcome': 'badreq', 'source': 'Nansen',
                'freshness_seconds': None, 'cost_requests': 0, 'cost_credits': 0,
                'caveats': [], 'payload': None, 'lang': lg, 'rendered_text': None,
                'refusal': ('Unknown screen.' if lg == 'en' else 'Неизвестный экран.')}

    # ── 2. РЕПЕТИЦИЯ РЕШАЕТСЯ ДО ЛИМИТОВ И ДО СЕТИ: она ничего не тратит.
    if req.get('rh'):
        return _rehearsal(scene, lg)

    params = {}
    if scene in ('pm_reputation', 'pm_positions'):
        # ОБА ЭКРАНА РЫНКА ЧИТАЮТ ОДНО И ТО ЖЕ ПОЛЕ СИГНАЛА (`mk`), и это не экономия: номер
        # рынка едет между экранами ОДНИМ способом, поэтому новый экран не требует ни новой
        # формы на Воркере, ни нового способа его туда положить.
        params['market'] = str(req.get('mk') or '')[:40]
        if not params['market']:
            return {'scene': scene, 'outcome': 'badreq', 'source': 'Nansen',
                    'freshness_seconds': None, 'cost_requests': 0, 'cost_credits': 0,
                    'caveats': [], 'payload': None, 'lang': lg, 'rendered_text': None,
                    'refusal': ('This screen needs a market id.' if lg == 'en'
                                else 'Этому экрану нужен номер рынка.')}
    elif scene == 'liq_map':
        params['token'] = str(req.get('tk') or '')[:12].upper()
        if not params['token']:
            return {'scene': scene, 'outcome': 'badreq', 'source': 'Nansen',
                    'freshness_seconds': None, 'cost_requests': 0, 'cost_credits': 0,
                    'caveats': [], 'payload': None, 'lang': lg, 'rendered_text': None,
                    'refusal': ('This screen needs a token ticker.' if lg == 'en'
                                else 'Этому экрану нужен тикер токена.')}

    # ── 3. ЛИМИТЫ - ТЕ ЖЕ, ЧТО У БОТА НА ЭТИХ ЖЕ ЭКРАНАХ, И ПРОВЕРЯЮТСЯ ДО СЕТИ.
    #
    # ПОЧЕМУ ЗДЕСЬ ТОЛЬКО ОБЩИЙ КАП, А НЕ СУТОЧНЫЙ ЛИМИТ ЧЕЛОВЕКА. В боте личный лимит стоит
    # ТОЛЬКО НА АГЕНТА (200/750 кредитов за вопрос); структурные экраны по 1-5 кредитов не
    # ограничены вовсе - так записано в `nansen_limits`. Все три сцены мини-аппа структурные,
    # значит применить к ним агентский счётчик значило бы ввести ограничение, которого у бота
    # НЕТ: человек открыл бы карту ликвидаций в чате бесплатно, а в мини-аппе получил бы
    # «вопросы на сегодня кончились». Это ровно то расхождение поверхностей, против которого
    # Закон 0, только не в числах, а в правилах.
    # ЖИВОЙ ПРОМАХ: первая редакция звала `L.check(uid, ...)` и на третьем прогоне выдала
    # `quota_user` на карту ликвидаций - поймано до прода, на своём же тесте.
    #
    # ОБЩИЙ КАП ПРОВЕРЯЕТСЯ, И ПРОВЕРЯЕТСЯ ЗНАНИЕМ ЦЕНЫ: пускать экран за 30, когда до капа
    # осталось 10, значит перейти его молча.
    import nansen_limits as L
    import nansen_log as T
    _cost = int(SCENE_COST.get(scene, 5))
    _left = None
    try:
        if uid not in _admins():
            _left = L.cap_left()          # None = общий кап выключен
    except Exception as e:                        # noqa: BLE001
        print('[nansen_gate] общий кап не прочитался (%s) - пускаю экран' % str(e)[:100])
        _left = None
    if _left is not None and _left < _cost:
        # ОТКАЗ ПО ЛИМИТУ - ТОЖЕ СТРОКА ТЕЛЕМЕТРИИ, и пишется ДО обращения к площадке:
        # «сто человек упёрлись в кап» и «сто человек не пришли» с виду одинаковы, а решения
        # у них противоположные.
        T.note_quota(scene, uid)
        return {'scene': scene, 'outcome': 'nocredits', 'source': 'Nansen',
                'freshness_seconds': None, 'cost_requests': 0, 'cost_credits': 0,
                'caveats': [], 'payload': None, 'lang': lg, 'rendered_text': None,
                'refusal': L.refusal_text('shared', lg, left_cap=_left)}

    # ── 4. СЦЕНА ТЕЛЕМЕТРИИ: ТА ЖЕ СЦЕНА, ДРУГАЯ ПОВЕРХНОСТЬ.
    with _scene_ctx(scene, uid):
        if scene in ('liq_map', 'perp_risk'):
            # ОДИН ЗАПРОС К HYPERLIQUID НА ОБА ЭКРАНА: `metaAndAssetCtxs` возвращает ВСЕ коины
            # сразу, и прежний цикл «по цене на токен» тянул один и тот же ответ четыре раза.
            _uni = _hl_universe()
            if scene == 'liq_map':
                params['mark'] = (_uni.get(params['token']) or {}).get('mark') or None
                # МАСШТАБ КАРТЫ ПРИЕЗЖАЕТ ОТ ЧЕЛОВЕКА И ПРОВЕРЯЕТСЯ ПО ЗАКРЫТОМУ СПИСКУ
                # НА БОТЕ (`liq_zoom_ok`), а не на Воркере: реестр ступеней один, и он в
                # слое чисел. Чужое значение молча становится умолчанием - подгонять его к
                # ближайшей ступени нельзя, это ответ на незаданный вопрос.
                params['zoom'] = req.get('zn')
                # ЧИСЛО УРОВНЕЙ - ТА ЖЕ ИСТОРИЯ: закрытый список на боте, форма на Воркере.
                params['buckets'] = req.get('bk')
                # СПИСОК ТИКЕРОВ ЕДЕТ ВМЕСТЕ С КАРТОЙ, И ЭТО ОТВЕТ НА ЖИВОЙ ВОПРОС: «почему
                # карты только по четырём?». Четыре были ЗАШИТЫ в страницу, то есть список
                # устаревал молча. Теперь он измерен - топ по суточному объёму самой площадки,
                # где висит это плечо. Площадка молчит - едет пустой список, и страница
                # показывает свои четыре как запас.
                params['tokens'] = _top_tokens(_uni, 10)
            else:
                # БОРД СРАВНИВАЕТ ТОП ПО ОБЪЁМУ, А НЕ ФИКСИРОВАННУЮ ЧЕТВЁРКУ. Замороженный
                # список однажды сравнивает то, чем уже никто не торгует.
                _toks = tuple(_top_tokens(_uni, 4)) or S.PERP_BOARD_TOKENS
                params['tokens'] = _toks
                params['marks'] = {t: (_uni.get(t) or {}).get('mark') or None for t in _toks}
        env = S.scene_data(scene, params, lg, bot_un)
    # СПИСАНИЯ АГЕНТСКОГО СЧЁТЧИКА ЗДЕСЬ НЕТ НАРОЧНО (`L.spend` не зовётся): он считает
    # вопросы к агенту, а структурный экран - не вопрос к агенту. Расход кредитов при этом
    # посчитан: его пишет телеметрия строкой на каждый сетевой вызов, и общий кап читает
    # именно её. Второй счётчик рядом с первым разошёлся бы с ним на первой правке.
    env['surface'] = 'miniapp'
    return _strip_private(env)


#: КЭШ ВСЕЛЕННОЙ ПЕРПОВ HYPERLIQUID: (время, словарь). Тридцать секунд - не про экономию
#: чужого API, а про то, чтобы ОДИН экран не спрашивал одно и то же дважды: борду нужны цены по
#: четырём токенам, карте - цена и список тикеров, и всё это один и тот же ответ.
_UNI_TTL = 30.0
_UNI = [0.0, {}]


def _hl_universe():
    """Все перп-коины Hyperliquid: {ТИКЕР: {mark, vol24, ...}}. -> dict (может быть пустым).

    ПУСТОЙ СЛОВАРЬ - ДОПУСТИМЫЙ ОТВЕТ, а не ошибка экрана: Hyperliquid не Nansen, его молчание
    лишает карту отметки «мы здесь» и списка тикеров, но не самой карты. Выдуманная цена дала бы
    отметку, которой никто не мерил, а выдуманный список тикеров - кнопки на токены, которых на
    площадке может не быть.
    """
    import time as _t
    if _UNI[1] and (_t.time() - _UNI[0]) < _UNI_TTL:
        return _UNI[1]
    try:
        import asyncio
        import oc_perps as _hl
        _p = os.path.join(ROOT, 'onchain')
        if _p not in sys.path:
            sys.path.insert(0, _p)
        uni = asyncio.run(_hl.hl_universe()) or {}
    except Exception as e:                        # noqa: BLE001
        print('[nansen_gate] вселенная перпов не взялась: %s' % str(e)[:100])
        return {}
    _UNI[0], _UNI[1] = _t.time(), uni
    return uni


