# -*- coding: utf-8 -*-
"""alert_log.py — ОДНА строка в лог на КАЖДУЮ отправку алерта в личку.

ЗАЧЕМ. 11 августа участник чата получил в личку алерт про рост позиции на $75 млн по
токену, которого не ждал. Разобрать случай по логам оказалось НЕВОЗМОЖНО: ни один
рассыльщик не писал, кому и по какой подписке он отправил, а bot.log к моменту разбора
провернулся. Единственным доказательством был скриншот у человека. Требование Ren дословно:
«каждая отправка алерта пишет строку [алерт] <модуль> uid=<кому> подписка=<чья> объект=<что>».

ФОРМАТ ОДИН НА ВСЕХ, И ЖИВЁТ ОН ЗДЕСЬ, а не восемью копиями по модулям: рассыльщиков
восемь (`oc_alerts`, `oc_whale_watch`, `scan_engine`, `nft_scanner`, `nft_alerts`,
`oc_unlocks`, `trad_charts`, `poly_leader_subs`), у каждого свой `_send`, и восемь
почти-одинаковых print'ов разошлись бы на первой же правке - ровно как разошлись сами
отправки (каждая шлёт в Telegram напрямую через httpx, минуя общую дверь).

СТРОКА ОТВЕЧАЕТ НА ТРИ ВОПРОСА, И ТРЕТИЙ - ГЛАВНЫЙ:
    кому   (`uid`)       - в чью личку ушло;
    чья    (`подписка`)  - чей это интерес по данным подписки;
    что    (`объект`)    - кошелёк/токен/лидер, о котором алерт.
ПОКА `uid` И `подписка` СЧИТАЮТСЯ ИЗ ОДНОГО МЕСТА, они всегда равны - и это нормально.
Смысл в том, что при расхождении лог САМ КРИЧИТ: несовпадение и есть утечка, и увидеть её
надо в момент отправки, а не через сутки по скриншоту.

ЛОГ - НЕ ПРЕДОХРАНИТЕЛЬ. Он не отменяет отправку и ничего не проверяет по существу:
доказательство корректной адресации даёт инвариант (`ал01` в tests/e2e/40_privacy.py),
который гоняет живую рассылку с двумя подписчиками и сверяет, что каждый получил ТОЛЬКО
своё. Эта строка нужна для РАЗБОРА следующего случая, а не вместо разбора.

ПЕЧАТАЕМ В stdout, а не в отдельный файл: у Ren главный лог - bot.log, туда уходит stdout
службы, и второй файл пришлось бы отдельно ротировать и отдельно не забывать смотреть.
Смотреть: grep -a '\[алерт\]' bot.log
"""


def _short(v, n=42):
    """Объект в строку лога: коротко и без переносов - иначе одна строка станет тремя."""
    s = str(v if v is not None else '').replace('\n', ' ').strip()
    return (s[:n] + '…') if len(s) > n else (s or '?')


def sent(module, uid, sub=None, obj=''):
    """Записать факт отправки алерта. Никогда не бросает и ничего не возвращает.

    module - имя модуля-рассыльщика ('oc_alerts', 'poly_leader_subs', …);
    uid    - КОМУ ушло (chat_id получателя);
    sub    - ЧЬЯ подписка (user_id из строки подписки). None - если основания нет вовсе,
             и это тоже факт: значит рассылка идёт не по подписке;
    obj    - О ЧЁМ алерт: адрес кошелька, символ токена, кошелёк лидера.

    НИКОГДА НЕ БРОСАЕТ: строка в логе не имеет права уронить рассылку. Но и молчать о
    своём сбое нельзя - иначе пропажу строк никто не заметит (закон о тихой поломке).
    """
    try:
        _line = ('[алерт] %s uid=%s подписка=%s объект=%s'
                 % (module, uid, ('?' if sub is None else sub), _short(obj)))
        # РАСХОЖДЕНИЕ ПОЛУЧАТЕЛЯ И ПОДПИСЧИКА - ЭТО УТЕЧКА, и называем мы её ВСЛУХ, а не
        # оставляем читателю лога сверять два числа глазами. Один такой случай уже был
        # разобран вручную по скриншоту, потому что в логе не было ничего.
        if sub is not None and str(sub) != str(uid):
            _line += ' ⚠️ ПОЛУЧАТЕЛЬ НЕ РАВЕН ПОДПИСЧИКУ - УТЕЧКА, СМОТРЕТЬ НЕМЕДЛЕННО'
        print(_line)
    except Exception as _e:
        print('[алерт] строка лога не собралась (%s: %s)' % (type(_e).__name__, _e))
    # ЗАПИСЬ В ЖУРНАЛ - ТОТ ЖЕ ИСТОЧНИК, ЧТО И СТРОКА ЛОГА (требование 5.2): человек
    # спросит «почему ты мне это прислал», и ответ обязан совпасть с логом дословно.
    _store(module, uid, sub, obj)



# ═══ «ПОЧЕМУ ТЫ МНЕ ЭТО ПРИСЛАЛ» — ОТВЕЧАЕТ БОТ, А НЕ РАЗБОР В БАЗЕ ═══
# Разбор случая 11.08 занял час и потребовал доступа к базе. Человек должен уметь выяснить
# это сам (требование 5). Источник ОДИН И ТОТ ЖЕ, что у строки лога: `sent()` и печатает, и
# кладёт запись - иначе команда и лог однажды разойдутся, и мы будем сверять два ответа на
# один вопрос (у нас это уже было с двумя отправками одного поста).
#
# ХРАНИМ В 'main', А НЕ В 'onchain', И ЭТО ОСОЗНАННО: рассыльщики живут в РАЗНЫХ ключах баз
# (onchain у кошельков, main у команд лички, свои у прочих), а журнал нужен ОДИН на все
# алерты - иначе команда должна была бы опрашивать четыре базы и знать, кто где живёт.
# Юзерская таблица -> уезжает при /delete_me (зарегистрирована в consent.HARD_DELETE).
KEEP_PER_USER = 20       # столько последних алертов помним на человека
_MODULES = {
    'oc_alerts':        ('движения и цена по счёту',
                         'кнопка «🔕 Отключить алерты по этому счёту» под алертом '
                         'или «Мои счета» → карточка счёта'),
    'oc_whale_watch':   ('слежка за китом', '«мои киты» → убрать из списка'),
    'scan_engine':      ('сканер по твоим условиям', '«сканер» → выключить условие'),
    'nft_scanner':      ('NFT-сканер', '«nft сканер выкл»'),
    'nft_alerts':       ('флор отслеживаемой NFT-коллекции', '«nft алерты» → убрать'),
    'oc_unlocks':       ('разлок токенов', '«анлоки» → убрать алерт'),
    'trad_alerts':      ('алерт по цене (традфин)', '«мои алерты» → убрать'),
    'poly_leader_subs': ('подписка на лидера Polymarket', '«мои лидеры» → отписаться'),
}


def _store(module, uid, sub, obj):
    """Положить запись в журнал. Никогда не бросает: журнал не имеет права ронять рассылку."""
    try:
        import db
        conn = db.get_conn('main', timeout=15, busy_timeout=5000)
        try:
            conn.execute("""CREATE TABLE IF NOT EXISTS alert_sent_log (
                id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER, ts INTEGER,
                module TEXT, sub_uid INTEGER, obj TEXT)""")
            conn.execute("INSERT INTO alert_sent_log(user_id,ts,module,sub_uid,obj) "
                         "VALUES(?,?,?,?,?)",
                         (int(uid), int(__import__('time').time()), str(module),
                          (None if sub is None else int(sub)), str(obj or '')[:120]))
            # ЖУРНАЛ НЕ РАСТЁТ БЕСКОНЕЧНО: держим последние KEEP_PER_USER на человека.
            # Чистим ТУТ ЖЕ, а не отдельной джобой - джобу пришлось бы не забыть завести.
            conn.execute("DELETE FROM alert_sent_log WHERE user_id=? AND id NOT IN "
                         "(SELECT id FROM alert_sent_log WHERE user_id=? "
                         " ORDER BY id DESC LIMIT ?)", (int(uid), int(uid), KEEP_PER_USER))
            conn.commit()
        finally:
            conn.close()
    except Exception as e:
        print('[алерт] журнал не записан (%s: %s)' % (type(e).__name__, str(e)[:90]))


def last_for(uid, limit=5):
    """Последние алерты человека. -> [(ts, module, sub_uid, obj)], новые первыми."""
    try:
        import db
        conn = db.get_conn('main', timeout=15, busy_timeout=5000)
        try:
            rows = conn.execute("SELECT ts, module, sub_uid, obj FROM alert_sent_log "
                                "WHERE user_id=? ORDER BY id DESC LIMIT ?",
                                (int(uid), int(limit))).fetchall()
            # ЧИТАЕМ ПО ИНДЕКСУ: на PG строки курсора не поддерживают доступ по имени.
            return [(r[0], r[1], r[2], r[3]) for r in (rows or [])]
        finally:
            conn.close()
    except Exception as e:
        print('[алерт] журнал не прочитан (%s: %s)' % (type(e).__name__, str(e)[:90]))
        return []


def explain(uid, limit=3):
    """Ответ на «почему ты мне это прислал». -> str.

    ОТВЕЧАЕМ ПО ФАКТУ ОТПРАВКИ, А НЕ ПО ДОГАДКЕ: берём записи журнала. Пусто - так и
    говорим: «не нахожу», а не выдумываем причину (у нас уже был рапорт без факта).
    """
    _rows = last_for(uid, limit=limit)
    if not _rows:
        return ('Не нахожу в журнале алертов, отправленных тебе. Либо их не было, либо они '
                'ушли до того, как я стал записывать (журнал храню на последние %d штук). '
                'Если сообщение перед тобой - пришли его мне пересылкой, разберусь по тексту.'
                % KEEP_PER_USER)
    import time as _t
    _out = ['🔎 <b>Последние алерты, которые я тебе отправил</b>']
    for _ts, _mod, _sub, _obj in _rows:
        _name, _how = _MODULES.get(_mod, (_mod, 'напиши «настройки алертов»'))
        _when = _t.strftime('%d.%m %H:%M', _t.localtime(int(_ts or 0)))
        _out.append('\n<b>%s</b> — %s' % (_when, _name))
        _out.append('· объект: %s' % (_obj or 'не назван'))
        # ЧЬЯ ПОДПИСКА - НАЗЫВАЕМ ВСЛУХ. Если она не твоя, это и есть тот случай, который
        # мы разбирали час по скриншоту: человек имеет право увидеть расхождение сам.
        if _sub is not None and str(_sub) != str(uid):
            _out.append('· ⚠️ подписка ЧУЖАЯ (uid %s) — это сбой, покажи это владельцу бота'
                        % _sub)
        else:
            _out.append('· подписка: твоя')
        _out.append('· как отключить: %s' % _how)
        _out.append('· функция: <code>%s</code>' % _mod)
    return '\n'.join(_out)
