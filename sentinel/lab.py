# -*- coding: utf-8 -*-
"""sentinel/lab.py — ЛАБОРАТОРИЯ: исторические холдинги смарт-денег под отдельным капом.

РЕШЕНИЕ ВЛАДЕЛЬЦА 25.09: «Дневной кап - 10к по Лаборатория бэктеста» и «Ну пробуй че, потестируем
Качество держателей как режим (3.5)». Оба пункта роудмапа закрываются одной дверью, потому что
оба стоят на одной ручке - `smart-money/historical-holdings`.

ПОЧЕМУ КАП ОТДЕЛЬНЫЙ ОТ ДОЗОРНОГО. Дозор тратит понемногу и постоянно, лаборатория - редко и
много (дневные снимки за годы). Общий кап на двоих означал бы, что один прогон исследования
глушит алерты на сутки, и человек узнал бы об этом МОЛЧАНИЕМ. Поэтому у лаборатории свой
счётчик и своя строка расхода.

ЧТО ИЗВЕСТНО О РУЧКЕ ДО ЖИВОЙ ПРОБЫ (и что придётся проверить руками):
  * beta, дневные снимки, окно около четырёх лет, серверный кэш 5 минут на сегодня и 7 суток на
    прошлое; сегодняшняя строка живая и потому НЕПОЛНАЯ;
  * ЕЁ НЕТ В НАШЕЙ ОПИСИ 59 МАРШРУТОВ - значит схема тела запроса у нас не снята, и первый
    вызов идёт через `_post_fix`, который правит тело по словам площадки;
  * метка `Fund` для текущих холдингов объявлена устаревшей с 2026-09-09 - на истории она
    встречается, и считать по ней «фонды вышли» нельзя, это смена разметки, а не движение денег.

ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО ДОЗОРНОМУ. Все наши сигналы отвечают на «что сейчас». Исторические
холдинги отвечают на другое: «СОСТАВ ДЕРЖАТЕЛЕЙ СМЕНИЛСЯ» - умные деньги заходили месяц, а на
этой неделе выходят. Это режим, а не событие, и он объясняет движения, которых иначе не понять.

ГРАНИЦА: НИ ОДНОГО АВТОМАТИЧЕСКОГО ВЫЗОВА. Лаборатория запускается РУКАМИ и печатает план
расхода до того, как что-то потратит. Автономная трата у нас уже есть у дозорного, и вторая,
которая может съесть десять тысяч кредитов за прогон, обязана начинаться с человека.
"""

import os

from . import config, store


def spend_left():
    """Сколько кредитов лаборатории осталось сегодня. -> int | None (None = кап выключен)."""
    cap = config.lab_day_credits()
    if cap <= 0:
        return None
    used, _ = store.spend_today(day=_lab_day())
    return max(0, cap - used)


def _lab_day():
    """СВОЙ ключ суток для расхода лаборатории. -> str.

    Отдельная строка в той же таблице, а не своя таблица: расход считается одной дверью
    (`store.spend_add`), и разделение по КЛЮЧУ дня даёт два независимых счётчика без второго
    механизма. Ключ назван словом, чтобы в базе было видно, чей это расход.
    """
    import time
    return 'lab-%s' % time.strftime('%Y-%m-%d', time.gmtime())


def plan(tokens, days):
    """ПЛАН РАСХОДА ДО ТРАТЫ. -> (сколько вызовов, сколько кредитов, строка для человека).

    Печатается всегда и первым: инструмент, который может потратить десять тысяч кредитов,
    обязан сначала показать, что именно он собирается сделать (закон T1 проекта - предохранитель
    снимает человек, а для этого человек должен видеть цену).
    """
    calls = max(1, int(len(tokens or ()) or 1))
    credits = calls * _CREDITS_PER_CALL
    left = spend_left()
    line = ('План: %d вызов(ов) по %s токенам, окно %d дн -> около %d кредитов. '
            'Остаток лаборатории сегодня: %s'
            % (calls, len(tokens or ()) or '?', int(days), credits,
               ('без ограничения' if left is None else '%d' % left)))
    return calls, credits, line


#: ЦЕНА ВЫЗОВА В КРЕДИТАХ. Взята по верхней границе структурного вызова (5), потому что для этой
#: ручки цена ИСТОЧНИКОМ НЕ НАЗВАНА: занижать свой расход хуже, чем завысить (закон №22 -
#: неизмеренное считаем отдельной строкой, а не догадкой).
_CREDITS_PER_CALL = 5


def holdings(chain, token_address, days=30, dry_run=True):
    """Исторические холдинги смарт-денег по токену. -> (строки, отказ).

    `dry_run=True` ПО УМОЛЧАНИЮ, И ЭТО ПРЕДОХРАНИТЕЛЬ: сухой прогон печатает ровно то, что
    произойдёт в боевом режиме, и ничего не тратит. Снимает его человек аргументом, а не код.
    """
    calls, credits, line = plan([token_address], days)
    print('[lab] %s' % line)
    if dry_run:
        return [], 'сухой прогон: ничего не потрачено. Для живого вызова dry_run=False'
    left = spend_left()
    if left is not None and left < credits:
        return [], ('кап лаборатории не позволяет: нужно %d кредитов, осталось %d'
                    % (credits, left))
    try:
        import nansen_api as _n
        import nansen_log as _tele
        with _tele.scene('sentinel_watch', None, surface='sentinel'):
            rows = _n._post_fix('smart-money/historical-holdings',
                                # ИМЯ ПОЛЯ СНЯТО ЖИВЫМ ВЫЗОВОМ, А НЕ УГАДАНО. Первая редакция
                                # послала `date` и получила от площадки дословно:
                                # «Required field 'body -> date_range' is missing»
                                # (http 422, код missing_field, request_id 14c68271...).
                                # Ручки нет в нашей описи 59 маршрутов, поэтому схему назвала
                                # САМА площадка - это и есть измерение вместо догадки.
                                {'chain': _n._nc(chain), 'token_address': token_address,
                                 'date_range': _n._date_range(days),
                                 'pagination': {'page': 1, 'per_page': 100}},
                                ckey=None)
        store.spend_add(credits=credits, day=_lab_day())
    except Exception as e:
        return [], 'ручка не ответила: %s: %s' % (type(e).__name__, str(e)[:120])
    if not rows:
        # ПУСТОТА ЗДЕСЬ ОСОБЕННО ОПАСНА: ручка beta, и «данных нет» может означать «схема тела
        # не та». Поэтому причина берётся из коробки вызова, а не придумывается.
        try:
            import nansen_api as _n2
            return [], 'пусто: %s' % _n2.fail_reason('empty')
        except Exception:
            return [], 'пусто (причина не прочитана)'
    return (rows if isinstance(rows, list) else [rows]), None
