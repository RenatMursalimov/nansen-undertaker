# -*- coding: utf-8 -*-
"""sentinel/lab.py — ЛАБОРАТОРИЯ: исторические холдинги смарт-денег под отдельным капом.

РЕШЕНИЕ ВЛАДЕЛЬЦА 25.09: «Дневной кап - 10к по Лаборатория бэктеста» и «Ну пробуй че, потестируем
Качество держателей как режим (3.5)». Оба пункта роудмапа закрываются одной дверью, потому что
оба стоят на одной ручке - `smart-money/historical-holdings`.

ПОЧЕМУ КАП ОТДЕЛЬНЫЙ ОТ ДОЗОРНОГО. Дозор тратит понемногу и постоянно, лаборатория - редко и
много (дневные снимки за годы). Общий кап на двоих означал бы, что один прогон исследования
глушит алерты на сутки, и человек узнал бы об этом МОЛЧАНИЕМ. Поэтому у лаборатории свой
счётчик и своя строка расхода.

ЧТО ИЗВЕСТНО О РУЧКЕ ДО ЖИВОЙ ПРОБЫ (и что придётся проверить руками):
  * beta, дневные снимки, окно около четырёх лет, серверный кэш 5 минут на сегодня и 7 суток на
    прошлое; сегодняшняя строка живая и потому НЕПОЛНАЯ;
  * ЕЁ НЕТ В НАШЕЙ ОПИСИ 59 МАРШРУТОВ - значит схема тела запроса у нас не снята, и первый
    вызов идёт через `_post_fix`, который правит тело по словам площадки;
  * метка `Fund` для текущих холдингов объявлена устаревшей с 2026-09-09 - на истории она
    встречается, и считать по ней «фонды вышли» нельзя, это смена разметки, а не движение денег.

ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО ДОЗОРНОМУ. Все наши сигналы отвечают на «что сейчас». Исторические
холдинги отвечают на другое: «СОСТАВ ДЕРЖАТЕЛЕЙ СМЕНИЛСЯ» - умные деньги заходили месяц, а на
этой неделе выходят. Это режим, а не событие, и он объясняет движения, которых иначе не понять.

ГРАНИЦА: НИ ОДНОГО АВТОМАТИЧЕСКОГО ВЫЗОВА. Лаборатория запускается РУКАМИ и печатает план
расхода до того, как что-то потратит. Автономная трата у нас уже есть у дозорного, и вторая,
которая может съесть десять тысяч кредитов за прогон, обязана начинаться с человека.
"""

import os

from . import config, store


def spend_left():
    """Сколько кредитов лаборатории осталось сегодня. -> int | None (None = кап выключен).

    КАП БЕРЁМ ЧЕРЕЗ `store.lab_cap`, А НЕ ИЗ `config` НАПРЯМУЮ: с круга 9 его правит владелец
    кнопкой, и значение из базы сильнее `.env`. Читать здесь `config` значило бы показывать
    план по старому числу, а тратить по новому.
    """
    cap = store.lab_cap()
    if cap <= 0:
        return None
    used, _ = store.spend_today(day=_lab_day())
    return max(0, cap - used)


def _lab_day():
    """СВОЙ ключ суток для расхода лаборатории. -> str.

    Отдельная строка в той же таблице, а не своя таблица: расход считается одной дверью
    (`store.spend_add`), и разделение по КЛЮЧУ дня даёт два независимых счётчика без второго
    механизма. Ключ назван словом, чтобы в базе было видно, чей это расход.
    """
    import time
    return 'lab-%s' % time.strftime('%Y-%m-%d', time.gmtime())


def plan(tokens, days):
    """ПЛАН РАСХОДА ДО ТРАТЫ. -> (сколько вызовов, сколько кредитов, строка для человека).

    Печатается всегда и первым: инструмент, который может потратить десять тысяч кредитов,
    обязан сначала показать, что именно он собирается сделать (закон T1 проекта - предохранитель
    снимает человек, а для этого человек должен видеть цену).
    """
    calls = max(1, int(len(tokens or ()) or 1))
    credits = calls * _CREDITS_PER_CALL
    left = spend_left()
    line = ('План: %d вызов(ов) по %s токенам, окно %d дн -> около %d кредитов. '
            'Остаток лаборатории сегодня: %s'
            % (calls, len(tokens or ()) or '?', int(days), credits,
               ('без ограничения' if left is None else '%d' % left)))
    return calls, credits, line


#: ЦЕНА ВЫЗОВА В КРЕДИТАХ. Взята по верхней границе структурного вызова (5), потому что для этой
#: ручки цена ИСТОЧНИКОМ НЕ НАЗВАНА: занижать свой расход хуже, чем завысить (закон №22 -
#: неизмеренное считаем отдельной строкой, а не догадкой).
_CREDITS_PER_CALL = 5


def holdings(chain, token_address, days=30, dry_run=True):
    """Исторические холдинги смарт-денег по токену. -> (строки, отказ).

    `dry_run=True` ПО УМОЛЧАНИЮ, И ЭТО ПРЕДОХРАНИТЕЛЬ: сухой прогон печатает ровно то, что
    произойдёт в боевом режиме, и ничего не тратит. Снимает его человек аргументом, а не код.
    """
    calls, credits, line = plan([token_address], days)
    print('[lab] %s' % line)
    if dry_run:
        return [], 'сухой прогон: ничего не потрачено. Для живого вызова dry_run=False'
    left = spend_left()
    if left is not None and left < credits:
        return [], ('кап лаборатории не позволяет: нужно %d кредитов, осталось %d'
                    % (credits, left))
    _EP = 'smart-money/historical-holdings'
    try:
        import nansen_api as _n
        import nansen_log as _tele
        with _tele.scene('sentinel_watch', None, surface='sentinel'):
            rows = _n._post_fix(_EP,
                                # СХЕМУ НАЗВАЛА САМА ПЛОЩАДКА, ДВАЖДЫ, И ОБА РАЗА ЖИВЫМ ВЫЗОВОМ
                                # ВЛАДЕЛЬЦА - догадок здесь нет ни одной:
                                #  1) «Required field 'body -> date_range' is missing» (422,
                                #     missing_field) - значит поле зовётся `date_range`, а не
                                #     `date`, как у структурных ручек;
                                #  2) «Date format not allowed: '2026-08-26T00:00:00Z'. Please
                                #     use YYYY-MM-DD format instead. Time components (T, :, Z,
                                #     +) are not supported for this endpoint» (422,
                                #     invalid_date_format) - значит ОБЩИЙ `_n._date_range`,
                                #     который отдаёт ISO со временем и годами работает на
                                #     остальных ручках, ЗДЕСЬ НЕ ГОДИТСЯ.
                                # ПОЭТОМУ СВОЙ `_days_range`, А НЕ ПРАВКА ОБЩЕГО: требования у
                                # ручек ОДНОЙ площадки разные, и «починив» общий, мы сломали бы
                                # девятнадцать работающих вызовов ради одного нового.
                                #  3) «Required field 'body -> chains' is missing. Must be a
                                #     list of chain names, e.g., ["ethereum", "solana"]» (422,
                                #     missing_field) - то есть поле зовётся `chains` и это
                                #     СПИСОК, а не строка `chain`, как у всех остальных ручек.
                                #  4) «Field 'token_address' is not recognized» (422,
                                #     unknown_field) - и ЭТО САМОЕ ВАЖНОЕ ИЗ ЧЕТЫРЁХ. Ручка не
                                #     принимает токен ВООБЩЕ: она отдаёт СРЕЗ ПО СЕТИ - топ
                                #     holdings смарт-денег на дату. Наш токен в ответе есть, но
                                #     как ОДНА ИЗ СТРОК, а не как предмет запроса.
                                {'chains': [_n._nc(chain)],
                                 'date_range': _days_range(days),
                                 'pagination': {'page': 1, 'per_page': 100}},
                                ckey=None)
            # ═══ ПРИЧИНУ ЧИТАЕМ ВНУТРИ КОРОБКИ, А НЕ ПОСЛЕ ЕЁ ЗАКРЫТИЯ ═══
            # ЖИВОЙ ПРОГОН ВЛАДЕЛЬЦА 26.09 ПОКАЗАЛ НАСТОЯЩИЙ ДЕФЕКТ: площадка ответила
            # осмысленным 422 с текстом про формат даты, в логе он был, а человек получил
            # «пусто: empty». Причина не в площадке: `fail_reason()` читает ТЕКУЩУЮ коробку
            # вызова (`nansen_log.box`), а стояла она ПОСЛЕ выхода из `with scene(...)` - то
            # есть спрашивала уже другую, пустую коробку. Ответ «empty» был честным ответом на
            # неправильно заданный вопрос.
            # КЛАСС ОШИБКИ ТОТ ЖЕ, ЧТО У КРУГА 8: решение (или чтение) вне той области, в
            # которой живёт нужное состояние. Здесь - область контекстного менеджера.
            _why = _n.fail_reason('empty') if not rows else None
            # И СЛОВА ПЛОЩАДКИ - ОТДЕЛЬНО ОТ КЛАССА ОТКАЗА. «http»/«badreq» говорит «это наш
            # баг, он в логе», а у владельца лога под рукой нет; `provider_said` отдаёт
            # машиночитаемое объяснение (`plain=True` - без разметки, мы печатаем в терминал).
            # ═══ И ТОЛЬКО КОГДА ПЛОЩАДКА ПРАВДА НАС ОТВЕРГЛА ═══
            # `_LAST_ERR` живёт НА ПРОЦЕСС. `provider_said` сверяет ПУТЬ и потому не покажет
            # ошибку чужой ручки - но от ошибки ПРОШЛОГО вызова ТОЙ ЖЕ ручки она не спасает.
            # Живая проба это и поймала: второй вызов вернул честный пустой 200, а к нему
            # приклеилась жалоба на формат даты из первого - то есть человек читал бы объяснение
            # несуществующей проблемы. Пустой ответ 200 значит, что площадка НЕ ЖАЛОВАЛАСЬ, и
            # своих слов у неё в этот раз нет.
            _said = (_n.provider_said(_EP, plain=True)
                     if (not rows and _why not in (None, 'ok', 'empty')) else '')
        # ═══ РАСХОД СЧИТАЕМ ПО ТОМУ, ОТВЕТИЛА ЛИ ПЛОЩАДКА, А НЕ ПО ФАКТУ ВЫЗОВА ═══
        # ОТВЕРГНУТЫЙ ЗАПРОС (422 «формат даты не тот») КРЕДИТОВ НЕ СТОИТ: площадка не считала
        # данные, она нас не поняла. Записав его в расход, мы сами уменьшили бы свой кап за
        # СВОЮ ЖЕ ошибку в теле - и в живом прогоне владельца это уже случилось: остаток стал
        # 9995 при нуле полученных строк.
        # А ВОТ ПУСТОЙ ОТВЕТ 200 СТОИТ: площадка отработала, данных по токену просто нет.
        # Различить их можно ровно одним способом - классом отказа из коробки вызова: 'empty'
        # значит «ответила и данных нет», всё остальное значит «не ответила».
        if rows or _why == 'empty':
            store.spend_add(credits=credits, day=_lab_day())
    except Exception as e:
        return [], 'ручка не ответила: %s: %s' % (type(e).__name__, str(e)[:120])
    if not rows:
        # ПУСТОТА ЗДЕСЬ ОСОБЕННО ОПАСНА: ручка beta, и «данных нет» может означать «схема тела
        # не та». Поэтому причина берётся из коробки вызова, а не придумывается.
        return [], ('%s%s' % (_why or 'пусто',
                              (' — площадка сказала: %s' % _said) if _said else ''))
    # ═══ ОТВЕЧАЕМ НА СВОЙ ВОПРОС, А НЕ НА ТОТ, КОТОРЫЙ ПОЛУЧИЛСЯ ═══
    # ЖИВОЙ ПРОГОН ВЛАДЕЛЬЦА 26.09 ВСКРЫЛ ДЕФЕКТ ХУЖЕ ПРЕЖНИХ. Ремонт схемы убрал поле
    # `token_address` (площадка его не знает), запрос прошёл, и функция вернула «строк: 1,
    # отказ: None» - то есть УСПЕХ. Но в этой одной строке лежал топ-100 holdings смарт-денег
    # ПО ВСЕЙ СЕТИ, а спрашивали мы про один токен. Ответ был не на наш вопрос, и никто об этом
    # не сказал: ровно «признак наличия не равен признаку пользы», только в самой злой форме -
    # данные есть, они настоящие, и они про другое.
    # УРОК ШИРЕ ЭТОЙ ФУНКЦИИ: ремонт тела запроса, убирающий СУЖАЮЩЕЕ поле, меняет СМЫСЛ
    # ответа. Молча принимать такой результат нельзя нигде.
    return _pick(rows, token_address, chain)


def _flatten(rows):
    """Строки ответа из вложенного `data`. -> list[dict].

    ФОРМА СНЯТА ЖИВЫМ ВЫЗОВОМ 26.09, а не предположена: ответ приходит как
    `[{'data': [...], 'pagination': {...}}]`, то есть один элемент с вложенным списком. Поля
    каждой строки: `date`, `chain`, `token_address`, `token_symbol`, `token_sectors`,
    `smart_money_labels`, `balance`, `value_usd`, `balance_24h_percent_change`,
    `holders_count`, `share_of_holdings_percent`, `token_age_days`, `market_cap_usd`.
    """
    out = []
    for r in (rows if isinstance(rows, list) else [rows]):
        if isinstance(r, dict) and isinstance(r.get('data'), list):
            out += [x for x in r['data'] if isinstance(x, dict)]
        elif isinstance(r, dict):
            out.append(r)
    return out


def _pick(rows, token_address, chain):
    """Наш токен из среза по сети. -> (строки, отказ).

    ТРИ РАЗНЫХ ОТВЕТА, И ПУТАТЬ ИХ НЕЛЬЗЯ:
      * токен найден -> отдаём ЕГО строку плюс место в списке (место и есть смысл: «седьмой по
        деньгам умных среди всех токенов сети» говорит больше, чем сам баланс);
      * токена в срезе нет -> это НЕ пустота и НЕ отказ, а осмысленный ответ: умные деньги его
        не держат (в топе, который вернула площадка). Так и говорим;
      * токен не назван вовсе -> отдаём срез целиком, потому что именно его и просили.
    """
    data = _flatten(rows)
    if not data:
        return [], 'ответ есть, но строк в нём нет - форма ответа могла смениться'
    if not token_address:
        return data, None
    want = str(token_address or '').strip().lower()
    # СОРТИРУЕМ САМИ ПО `value_usd`: площадка отдаёт уже по убыванию, но полагаться на чужой
    # порядок для утверждения «он седьмой» нельзя - это наше утверждение, и считать его нам.
    ordered = sorted(data, key=lambda x: -float(x.get('value_usd') or 0))
    for i, x in enumerate(ordered, 1):
        if str(x.get('token_address') or '').strip().lower() == want:
            row = dict(x)
            row['rank'] = i
            row['of'] = len(ordered)
            return [row], None
    return [], ('токена %s нет среди %d позиций умных денег на %s - они его не держат '
                '(это ответ, а не пустота)'
                % (token_address[:12] + '…', len(ordered), chain))


def _days_range(days):
    """Окно в КАЛЕНДАРНЫХ датах для этой ручки. -> {'from': 'ГГГГ-ММ-ДД', 'to': 'ГГГГ-ММ-ДД'}.

    ПОЧЕМУ НЕ ОБЩИЙ `nansen_api._date_range`. Он отдаёт ISO со временем
    (`2026-08-26T00:00:00Z`) и годами работает на девятнадцати других ручках. Эта ответила
    владельцу дословно: «Time components (T, :, Z, +) are not supported for this endpoint».
    Значит требование у РУЧКИ, а не у площадки, и правильный ответ - своя функция здесь, а не
    правка общей двери: у общей девятнадцать живых читателей, и «починив» её, мы сломали бы их.
    ВЕРХНЯЯ ГРАНИЦА - СЕГОДНЯ, и это не мелочь: сегодняшний дневной снимок у ручки ЖИВОЙ и
    потому НЕПОЛНЫЙ (дока: серверный кэш 5 минут на сегодня, 7 суток на прошлое). Считать по
    нему «фонды вышли» нельзя, и в разборе это должно быть видно.
    """
    import datetime as _dt
    to = _dt.datetime.utcnow().date()
    frm = to - _dt.timedelta(days=max(1, int(days)))
    return {'from': frm.strftime('%Y-%m-%d'), 'to': to.strftime('%Y-%m-%d')}
