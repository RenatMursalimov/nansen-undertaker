# КЛАСС АКТИВА ДЛЯ ПЛОЩАДОК БЕЗ ИМЁН (решение владельца 26.09)
#
# Hyperliquid и Lighter отдают вместо имени тикер, и класс по ним не определяется. Владелец
# велел брать класс у Variational ПО СОВПАДЕНИЮ ТИКЕРА, если там он определён, а иначе -
# 'unknown' (pre-IPO и Азию не угадывать). Справочник собирает ОПРАШИВАЮЩИЙ процесс из живого
# ответа Variational и кладёт в базу (`sentinel_cursor`): доставка и обогащение живут в ДРУГОМ
# процессе (бот), у которого своего опроса нет, и без базы у него справочник был бы пустым -
# ровно тот случай «в одном процессе знают, в другом нет», что уже стоил разбора.
# ══════════════════════════════════════════════════════════════════════════════════════════
BOOK_CURSOR = 'var_book'
_BOOK = {'map': {}, 'loaded_at': 0}
_BOOK_TTL_S = 600


def book_update(rows):
    """Справочник {тикер: [класс, имя]} из снимка Variational. -> сколько записей | None.

    Пишется в базу только при изменении: 553 строки раз в 30 секунд - это запись ради записи.
    Пустой снимок Variational (площадка упала) справочник НЕ стирает.
    """
    from .variational_feed import asset_class
    book = {}
    for x in rows or ():
        if (getattr(x, 'venue', 'variational') or 'variational') != 'variational':
            continue
        k = asset_class(x)
        book[str(x.ticker).upper()] = [k, str(x.name or '')]
    if not book:
        return None
    if book != _BOOK['map']:
        _BOOK['map'] = book
        _BOOK['loaded_at'] = int(__import__('time').time())
        try:
            import json as _j
            from . import store
            store.cursor_set(BOOK_CURSOR, _j.dumps(book, ensure_ascii=False))
        except Exception as e:                                # noqa: BLE001
            print('[sentinel] справочник классов не записан: %s' % str(e)[:100])
    return len(book)


def book_get():
    """Справочник из памяти или из базы (кэш на 10 минут). -> dict."""
    import time as _t
    now = int(_t.time())
    if _BOOK['map'] and now - _BOOK['loaded_at'] < _BOOK_TTL_S:
        return _BOOK['map']
    try:
        import json as _j
        from . import store
        raw = store.cursor_get(BOOK_CURSOR)
        if raw:
            _BOOK['map'] = _j.loads(raw) or {}
    except Exception as e:                                    # noqa: BLE001
        print('[sentinel] справочник классов не прочитан: %s' % str(e)[:100])
    _BOOK['loaded_at'] = now
    return _BOOK['map']


def book_class(ticker):
    """Класс по тикеру из справочника Variational. -> класс | None (тикера там нет)."""
    got = book_get().get(str(ticker or '').upper())
    return got[0] if got else None


def book_peek(ticker):
    """Класс по тикеру ТОЛЬКО из памяти процесса, без базы. -> класс | None."""
    got = (_BOOK['map'] or {}).get(str(ticker or '').upper())
    return got[0] if got else None


def book_name(ticker):
    """Полное имя по тикеру из справочника Variational. -> str | ''."""
    got = book_get().get(str(ticker or '').upper())
    return (got[1] if got else '') or ''


