# СЕССИЯ NYSE (ТЗ 2.5): АКЦИЯ И ФОНД ВНЕ ТОРГОВ - ТОЛЬКО В СВОДКУ
#
# Перп на акцию торгуется круглые сутки, а сама акция - нет. Вне сессии цену перпа двигает
# тонкая книга площадки без базового рынка, и «DELL +2.4%» в 03:00 UTC - это ход котировки
# маркет-мейкера, а не новость про Dell. Звонить им нельзя, скрыть - потерять: событие уходит в
# сводку с причиной словами.
# ЧАСЫ - ПО НЬЮ-ЙОРКУ, А НЕ ФИКСИРОВАННЫМ UTC. ТЗ назвало 13:30-20:00 UTC - это 9:30-16:00 по
# летнему нью-йоркскому времени. С первого воскресенья ноября сессия сдвигается на 14:30-21:00
# UTC, и фиксированное окно час в сутки звонило бы по закрытой бирже, а час молчало бы по
# открытой. Если в системе нет базы часовых поясов, берётся окно ТЗ, и это сказано в ответе.
# ПРАЗДНИКИ НЕ УЧИТЫВАЕМ (решение ТЗ): в праздник биржа закрыта, а мы считаем её открытой -
# ошибка в сторону лишнего звонка, раз в несколько недель, и она названа здесь.
# ══════════════════════════════════════════════════════════════════════════════════════════
SESSION_CLASSES = ('equity', 'fund')
_NY_OPEN_MIN, _NY_CLOSE_MIN = 9 * 60 + 30, 16 * 60
_UTC_OPEN_MIN, _UTC_CLOSE_MIN = 13 * 60 + 30, 20 * 60
#: ═══ ИНСТРУМЕНТЫ НЕ С NYSE - ИМЕНОВАННЫМ РЕЕСТРОМ (решение владельца 26.09) ═══
#: SK hynix (SKHY) торгуется в Корее, и часы NYSE для него неверны: в 03:00 UTC его биржа
#: открыта, а мы считали её закрытой. KRX - 09:00-15:30 по Сеулу, то есть 00:00-06:30 UTC пн-пт:
#: в Корее нет перехода на летнее время, поэтому окно в UTC фиксированное и честное.
#: РЕЕСТР, А НЕ УГАДЫВАНИЕ: остальные азиатские и pre-IPO инструменты (Lighter: SAMSUNG, XIAOMI,
#: OPENAI) владелец велел не угадывать - у них класс 'unknown', и сессия их не режет.
SESSION_BY_TICKER = {'SKHY': 'KRX'}
_KRX_OPEN_MIN, _KRX_CLOSE_MIN = 0, 6 * 60 + 30


def nyse_open(ts):
    """Открыта ли NYSE в момент ts. -> (bool, источник: 'America/New_York' | 'UTC 13:30-20:00')."""
    import datetime as _dt
    try:
        from zoneinfo import ZoneInfo
        t = _dt.datetime.fromtimestamp(int(ts), ZoneInfo('America/New_York'))
        lo, hi, src = _NY_OPEN_MIN, _NY_CLOSE_MIN, 'America/New_York'
    except Exception:                                     # noqa: BLE001 - нет tzdata
        t = _dt.datetime.fromtimestamp(int(ts), _dt.timezone.utc)
        lo, hi, src = _UTC_OPEN_MIN, _UTC_CLOSE_MIN, 'UTC 13:30-20:00'
    m = t.hour * 60 + t.minute
    return (t.weekday() < 5 and lo <= m < hi), src


def krx_open(ts):
    """Открыта ли KRX (Корея) в момент ts. -> bool. 00:00-06:30 UTC пн-пт, без летнего времени."""
    import datetime as _dt
    t = _dt.datetime.fromtimestamp(int(ts), _dt.timezone.utc)
    m = t.hour * 60 + t.minute
    return t.weekday() < 5 and _KRX_OPEN_MIN <= m < _KRX_CLOSE_MIN


def exchange_open(ticker, ts):
    """Открыта ли РОДНАЯ биржа инструмента. -> (bool, имя биржи)."""
    ex = SESSION_BY_TICKER.get(str(ticker or '').upper(), 'NYSE')
    if ex == 'KRX':
        return krx_open(ts), 'KRX'
    return nyse_open(ts)[0], 'NYSE'


def session_note(klass, ts, lang='ru', ticker=None):
    """Причина «только в сводку» для акции/фонда вне сессии. -> str | None (сессия идёт/не акция)."""
    if klass not in SESSION_CLASSES:
        return None
    ok, _ex = exchange_open(ticker, ts)
    if ok:
        return None
    return ('биржа закрыта, перп на тонкой книге' if lang != 'en' else
            'exchange closed, the perp trades on a thin book')


