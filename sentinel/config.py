# -*- coding: utf-8 -*-
"""sentinel/config.py — ВСЕ пороги дозорного одним списком, читаются на каждом тике.

ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Порог, зашитый в детектор, меняется только деплоем, а подбирают его
живым рынком: «3% по MRNA» и «3% по какому-нибудь ZBT» — события разной редкости. Здесь
числа лежат в одном месте, читаются из окружения ПРИ КАЖДОМ обращении (не в момент импорта),
и поэтому правятся на сервере одной строкой в `.env` + рестарт, без правки кода.

ПОЧЕМУ ФУНКЦИИ, А НЕ КОНСТАНТЫ. Константа, прочитанная на импорте, замерзает в живом
процессе: модуль дозорного импортируется на старте бота, и `.env` после этого читать уже
некому. Тот же класс бага, что «в одном процессе живут две версии кода разного возраста».
Плюс тесты подменяют порог через окружение, не переимпортируя пакет.

ЕДИНИЦЫ НАЗВАНЫ В ИМЕНИ. `*_PCT` — проценты (3.0 = 3%), `*_SEC` — секунды, `*_USD` — доллары.
Порог без единицы в имени читается как «3» и через месяц никто не помнит, 3% это или 3 сигмы.
"""

import os


def _f(name, default):
    """Число из окружения. Мусор в переменной -> дефолт из кода + громкая строка.

    МОЛЧА БРАТЬ ДЕФОЛТ НЕЛЬЗЯ: опечатка в `.env` («3,5» вместо «3.5») иначе выглядит как
    работающий порог, а дозорный тихо работает по другому числу — и это НЕ видно ни в логе,
    ни в карточке.
    """
    raw = os.getenv(name)
    if raw is None or str(raw).strip() == '':
        return float(default)
    try:
        return float(str(raw).strip())
    except (TypeError, ValueError):
        print('[sentinel] %s=%r не число - беру %s из кода' % (name, raw, default))
        return float(default)


def _i(name, default):
    return int(_f(name, default))


# ── ОПРОС ПЛОЩАДКИ ─────────────────────────────────────────────────────────────────────────
# ЛИМИТ ПЛОЩАДКИ ЗАМЕРЕН, А НЕ УГАДАН: 10 запросов за 10 секунд с адреса (docs.variational.io).
# Живая проба 25.09 показала вторую причину не частить: три опроса с шагом 3с вернули
# ОДИНАКОВЫЕ числа, а `quotes.updated_at` отставал на 20-80с — то есть ниже ~10с новых данных
# просто нет, и учащение жжёт лимит без выигрыша. 15с = близко к живому и втрое ниже потолка.
def poll_sec():
    return max(10, _i('SENTINEL_POLL_SEC', 15))


def ring_days():
    """Сколько суток держим снимки. Нужны для сигмы и для отчёта попаданий."""
    return max(1, _i('SENTINEL_RING_DAYS', 7))


# ── КОТИРОВКА: СВЕЖЕСТЬ ЕСТЬ ВЕЛИЧИНА, А НЕ ФЛАГ ───────────────────────────────────────────
# Площадка кэширует котировки до 600с (ДОКА) и сама говорит возраст в `quotes.updated_at`.
# Поэтому возраст идёт в карточку ЧИСЛОМ и штрафует уверенность, а за порогом «протухло»
# событие не отправляется вовсе: алерт про цену, которой уже нет, — хуже молчания.
def quote_warn_sec():
    return max(30, _i('SENTINEL_QUOTE_WARN_SEC', 120))


def quote_stale_sec():
    return max(120, _i('SENTINEL_QUOTE_STALE_SEC', 600))


# ── ПОРОГИ СОБЫТИЙ ─────────────────────────────────────────────────────────────────────────
def move_pct_15m():
    return _f('SENTINEL_MOVE_PCT_15M', 3.0)


def move_pct_60m():
    return _f('SENTINEL_MOVE_PCT_60M', 6.0)


def z_min():
    """Во сколько сигм своей же 15-минутной волатильности должно уложиться движение.

    ЗАЧЕМ ПОВЕРХ ПРОЦЕНТА. 3% по MSTR и 3% по низколиквидному альту — события разной
    редкости, и один общий процент либо завалит человека мусором по альтам, либо не заметит
    настоящего движения по акции. Сигма считается по НАШИМ ЖЕ снимкам того же инструмента,
    то есть порог адаптируется сам и не требует таблицы «у кого какой порог».
    """
    return _f('SENTINEL_Z_MIN', 2.5)


def sigma_min_points():
    """Меньше этого числа снимков сигму не считаем и события по z не публикуем.

    ПУСТАЯ ВЫБОРКА ДАЁТ СИГМУ 0, А НОЛЬ В ЗНАМЕНАТЕЛЕ ДАЁТ БЕСКОНЕЧНУЮ УВЕРЕННОСТЬ — то есть
    первый же тик после рестарта выглядел бы как «движение в сто сигм». Признак наличия
    данных не равен признаку их достаточности.
    """
    return max(8, _i('SENTINEL_SIGMA_MIN_POINTS', 20))


def oi_pct():
    """Скачок открытого интереса за окно, % к прежнему уровню."""
    return _f('SENTINEL_OI_PCT', 20.0)


def funding_apr_pct():
    """Годовой фандинг, выше которого ставка сама по себе является событием.

    Площадка отдаёт `funding_rate` и `funding_interval_s` (8ч у большинства инструментов);
    приводим к годовым ЗДЕСЬ, а не в голове читателя карточки.
    """
    return _f('SENTINEL_FUNDING_APR_PCT', 60.0)


def spread_mult():
    """Во сколько раз спред должен разойтись против своей же медианы, чтобы это было событием."""
    return _f('SENTINEL_SPREAD_MULT', 3.0)


def min_volume_usd():
    """Ниже этого 24ч-объёма инструмент в дозор не берём вовсе.

    Не «отфильтровать неинтересное», а убрать деление на пустоту: по инструменту без оборота
    любое движение марк-цены — это движение котировки маркет-мейкера, а не рынка.
    """
    return _f('SENTINEL_MIN_VOLUME_USD', 50000.0)


# ── СМАРТ-ЗАЖИГАНИЕ (Smart Ignition) ──────────────────────────────────────────────────────
def ign_wallets():
    """Сколько РАЗНЫХ адресов смарт-денег должны купить токен, чтобы это было зажиганием.

    Считаем адреса, а не сделки: десять сделок одного адреса — это один человек, и называть
    это «смарты заходят» было бы ложью ровно того сорта, от которого закон «признак наличия
    не равен признаку пользы».
    """
    return max(2, _i('SENTINEL_IGN_WALLETS', 3))


def ign_window_min():
    return max(15, _i('SENTINEL_IGN_WINDOW_MIN', 180))


def ign_usd():
    """Минимальный суммарный объём покупок смарт-денег в окне, $."""
    return _f('SENTINEL_IGN_USD', 150000.0)


def ign_mcap_bps():
    """Тот же объём В ДОЛЯХ КАПИТАЛИЗАЦИИ (базисные пункты).

    $150k по токену за $10B — шум, по токену за $3M — половина рынка. Абсолют и доля живут
    вместе: событием считаем выполнение ОБОИХ, где капитализация известна, и говорим вслух,
    когда она неизвестна.
    """
    return _f('SENTINEL_IGN_MCAP_BPS', 5.0)


# ── СКОЛЬКО ШУМА ДОПУСКАЕМ ────────────────────────────────────────────────────────────────
def cooldown_sec():
    """Пауза по паре (инструмент, вид события) на одного подписчика."""
    return max(300, _i('SENTINEL_COOLDOWN_SEC', 3600))


def daily_cap():
    """Сколько алертов в сутки на одного человека. Упор в кап пишется в лог строкой."""
    return max(1, _i('SENTINEL_DAILY_CAP', 25))


def max_tickers():
    """Сколько инструментов один человек может держать в дозоре."""
    return max(1, _i('SENTINEL_MAX_TICKERS', 15))


def nansen_day_credits():
    """Суточный потолок кредитов Нансена НА ДОЗОРНОГО, отдельно от общего капа.

    ЗАЧЕМ ВТОРОЙ КАП. Общий `nansen_limits.day_cap()` защищает бюджет целиком, но дозорный
    жжёт кредиты БЕЗ ЧЕЛОВЕКА — сам, по факту движения рынка. Один волатильный день мог бы
    съесть бюджет, из которого живут экраны по запросу, и человек увидел бы отказ там, где
    ничего не просил у дозорного. Поэтому у автономного расхода своя граница.
    """
    return max(0, _i('SENTINEL_NANSEN_DAY_CREDITS', 3000))


def enrich_on():
    """Обогащение (Нансен + твиттер + пересказ) — рубильником, отдельно от алертов.

    Базовая карточка бесплатна и детерминирована, обогащение стоит кредитов. Значит это
    ДВА разных решения, и одним флагом их связывать нельзя: выключив дорогое, человек не
    должен терять дешёвое.
    """
    return (os.getenv('SENTINEL_ENRICH') or '1').strip() not in ('0', 'no', 'off', 'false')
