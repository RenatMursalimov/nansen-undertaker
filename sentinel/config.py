# складывала их в поток, не нарушив ни одного правила. Правило, которое можно соблюсти 787 раз
# подряд, не ограничивает ничего.
#
# ПОЧЕМУ ПРЕСЕТ ЕГО НЕ СНИМАЕТ. Пресет «поток» существует для проверки и ставит потолок 120 в
# сутки - это осознанный выбор человека про КОЛИЧЕСТВО. Но никакой выбор не означает «залей меня
# так, чтобы я не смог нажать кнопку»: ошибиться в пресете легко, а выбраться из потока из
# интерфейса, который сам утонул в сообщениях, - нельзя. Поэтому темп ограничен ПОВЕРХ любых
# личных настроек, и снимается он только из `.env` (то есть руками, с сервера).
#
# И СОБЫТИЯ НЕ ВЫБРАСЫВАЮТСЯ. Всё, что не прошло предохранитель, ложится в дайджест и уезжает
# одним сообщением раз в десять минут, отсортированное ПО СИЛЕ. Молча съесть событие было бы
# второй ложью: человек не получил бы алерт и не узнал бы, что его не получил.
# ══════════════════════════════════════════════════════════════════════════════════════════
def burst_max():
    """Сколько ОТДЕЛЬНЫХ алертов человек может получить за окно `burst_window_sec`. -> int.

    ТРИ, А НЕ ДЕСЯТЬ: три сообщения подряд читаются, десять - листаются. Всё сверх этого не
    пропадает, а едет дайджестом; то есть цена ошибки в этом числе - задержка до десяти минут,
    а не потерянное событие.
    """
    return max(1, _i('SENTINEL_BURST_MAX', 3))


def burst_window_sec():
    """Окно предохранителя, секунды. -> int.

    ОКНО СКОЛЬЗЯЩЕЕ И СЧИТАЕТСЯ ПО ФАКТУ ДОСТАВКИ (`delivered_at`), а не по попыткам: отправка,
    которую Telegram не принял, телефон человека не тревожила и место в окне занимать не должна.
    """
    return max(60, _i('SENTINEL_BURST_WINDOW_SEC', 600))


def min_severity():
    """Ниже этой уверенности событие НЕ звонит, а идёт в дайджест. -> int (0..100).

    ЗАЧЕМ ПОРОГ СИЛЫ, ЕСЛИ ЕСТЬ ПОРОГИ ВЕЛИЧИН. Пороги величин отвечают «событие ли это»,
    уверенность отвечает «насколько мы в нём уверены» - и она у нас уже считается числом со
    штрафами (протухшая котировка, тонкая книга, мало снимков для сигмы). Событие на 40/100 -
    это то, о чём мы сами написали три причины сомневаться; будить им человека нельзя, а скрыть
    целиком - потерять. Дайджест - ровно то место, где такому событию место.
    75 - НЕ КРУГЛОЕ ЧИСЛО ИЗ ГОЛОВЫ: замер 25.09 показал, что карточки Hyperliquid стоят на
    75/100 (у площадки нет котировок на объём, и это штраф честный), а Variational с живой
    котировкой держится выше 85. То есть порог пропускает полноценные карточки обеих площадок и
    отсекает те, где данных не хватило.
    """
    return max(0, min(100, _i('SENTINEL_MIN_SEVERITY', 75)))


def digest_sec():
    """Как часто уезжает дайджест, секунды. -> int.

    ДЕСЯТЬ МИНУТ - ЭТО СРОК, ЗА КОТОРЫЙ ДАННЫЕ ЕЩЁ ЖИВЫ. Кэш котировок площадки 600с, и дайджест
    старше этого рассказывал бы о цене, которой уже нет. Ровно та же граница, что у
    `quote_stale_sec`, и она здесь не совпадение.
    """
    return max(60, _i('SENTINEL_DIGEST_SEC', 600))


def digest_max_rows():
    """Сколько строк влезает в одно сообщение дайджеста. -> int.

    Остаток НЕ теряется, а называется числом («и ещё 34 слабее») - иначе дайджест повторил бы
    ошибку, от которой создан: человек не знал бы, чего не увидел.
    """
    return max(3, _i('SENTINEL_DIGEST_MAX_ROWS', 12))


