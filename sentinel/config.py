# ЛИМИТ ПЛОЩАДКИ ЗАМЕРЕН, А НЕ УГАДАН: 10 запросов за 10 секунд с адреса (docs.variational.io).
# Живая проба 25.09 показала вторую причину не частить: три опроса с шагом 3с вернули
# ОДИНАКОВЫЕ числа, а `quotes.updated_at` отставал на 20-80с — то есть ниже ~10с новых данных
# просто нет, и учащение жжёт лимит без выигрыша. 15с = близко к живому и втрое ниже потолка.
def poll_sec():
    """Как часто опрашиваем площадку, секунды.

    ПОДНЯТ С 15 ДО 30 ПО ЗАМЕРУ 25.09. Лимит площадки (10 запросов/10с) позволял и 15с, но
    измерение показало, что новых чисел там нет: `mark_price` обновляется шагами по 1-2 минуты,
    а `quotes.updated_at` - раз в 40-90 секунд. Опрос вдвое чаще обновления данных не даёт ни
    одной новой точки и вдвое зря жжёт чужой лимит. 30с - всё ещё вдвое чаще, чем меняется
    котировка, то есть ни одного шага мы не пропускаем.
    """
    return max(10, _i('SENTINEL_POLL_SEC', 30))


