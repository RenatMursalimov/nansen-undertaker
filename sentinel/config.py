#: РОЛИ ПРОЦЕССА. Значение читается из `SENTINEL_ROLE`; всё, кроме `poller`, это `deliver`.
#: Список закрытый нарочно: опечатка в переменной («polller») не имеет права молча превратить
#: опрашивающего в доставщика - тогда опрос исчезнет, а служба останется `active`.
ROLE_POLLER = 'poller'
ROLE_DELIVER = 'deliver'


def role():
    """Роль ЭТОГО процесса в дозоре. -> 'poller' | 'deliver'.

    ═══ ПОЧЕМУ РОЛЬ, А НЕ ФЛАГ «ОПРОС НЕ В БОТЕ» (ЗАМЕР 26.09) ═══
    Флаг `SENTINEL_IN_BOT` отвечает на вопрос «ГДЕ идёт опрос», а `engine._ingest` читал его
    как ответ на другой вопрос - «моя ли это работа». Для бота эти два вопроса совпадали, для
    отдельного юнита - нет: `main.py` ставил себе `SENTINEL_IN_BOT=0` (честно: «опрос не в
    боте»), а `_ingest` понимал это как «опрашивает кто-то другой» и выходил. Итог на проде:
    юнит `sentinel` печатал «опрос у отдельного юнита», будучи этим самым юнитом, и оба
    процесса ждали смерти аренды. Опрос шёл раз в TTL+90с вместо 30с, кольцо было дырявым,
    сигма не набиралась НИКОГДА - то есть главный порог дозорного был невычислим.
    РОЛЬ ОТВЕЧАЕТ НА ВОПРОС О СЕБЕ, и перепутать её с вопросом о мире нельзя: `poller`
    опрашивает всегда, `deliver` - только если опрашивающий умер. Это разные утверждения, и
    теперь они разными словами и записаны.
    ДЕФОЛТ `deliver` НАМЕРЕННО: процесс, которому роль не выдали, не имеет права начать
    опрашивать сам - иначе забытая переменная снова даёт двух опрашивающих. Юнит выдаёт себе
    роль сам (`main.py`), и то же значение стоит в `deploy/sentinel.service`.
    """
    return (ROLE_POLLER if (os.getenv('SENTINEL_ROLE') or '').strip().lower() == ROLE_POLLER
            else ROLE_DELIVER)


def is_poller():
    """Этот процесс - опрашивающий. -> bool. Одна дверь, чтобы сравнение с ролью было в
    одном месте: строковое `== 'poller'`, размазанное по трём модулям, однажды разъедется."""
    return role() == ROLE_POLLER


def is_owner(uid):
    """Владелец/админ бота по `ADMIN_IDS`. -> bool. ОДНА ДВЕРЬ для всех модулей пакета.

    Переехала сюда из `ui._is_owner`, когда владельческая строка понадобилась ОТПРАВКЕ (строка
    расхода кредитов в сводке, ТЗ 2.7): `outbox` не может импортировать `ui` - тот импортирует
    `outbox`, и круг замкнулся бы. Пустой список = никому, а не всем.
    """
    import re as _re
    try:
        ids = {int(x) for x in _re.findall(r'-?\d+', os.getenv('ADMIN_IDS') or '')}
        return bool(ids) and int(uid) in ids
    except Exception:
        return False


def flow_uids():
    """Кому доступен пресет «Поток» (этап 4). -> set(uid): владельцы (`ADMIN_IDS`) и тестировщики
    (`SENTINEL_FLOW_UIDS`, через запятую). Остальным кнопка не рисуется: «Поток» - все виды, потолок
    120 в сутки, это инструмент проверки, а не режим для подписчика."""
    import re as _re
    out = set()
    for _k in ('ADMIN_IDS', 'SENTINEL_FLOW_UIDS'):
        try:
            out |= {int(x) for x in _re.findall(r'-?\d+', os.getenv(_k) or '')}
        except Exception:                                  # noqa: BLE001
            pass
    return out


