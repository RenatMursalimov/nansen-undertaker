# -*- coding: utf-8 -*-
"""sentinel/clusters.py — СОГЛАСОВАННЫЕ КОШЕЛЬКИ: три адреса могут быть одним человеком.

ПУНКТ 3.6 РОУДМАПА, И ОН НАЗВАН ТАМ ТОЧНО: «это ШТРАФ К УВЕРЕННОСТИ, а не новое событие — и
потому ценнее нового события». Здесь этот выбор и держится.

═══ ЗАЧЕМ ═══
Зажигание считает РАЗНЫЕ адреса, а не сделки, и это было первым честным решением модуля: десять
сделок одного адреса — один человек, и называть это «смарты заходят» было бы ложью. Но адрес
тоже не равен человеку. Пять кошельков, заведённых с одного, — это по-прежнему ОДИН участник,
и «5 умных адресов купили» в такой ситуации завышает силу сигнала ровно во столько раз, сколько
кошельков он себе нарезал. Сигнал не становится ложным — он становится СЛАБЕЕ, чем выглядит.

═══ ПОЧЕМУ ШТРАФ, А НЕ ОТМЕНА СОБЫТИЯ ═══
Связь адресов НЕ доказывает злого умысла: биржи заводят клиентские кошельки, фонды разносят
позицию по адресам ради операционной гигиены, боты держат исполнителей отдельно от казны. Отменив
событие, мы выбросили бы настоящие покупки. Поэтому число независимых участников пересчитывается,
а причина пишется в карточку словами — решение остаётся человеку, и оно у него обосновано.

═══ ПОЧЕМУ НЕ В `judge` ═══
`ignition.judge` — ЧИСТАЯ функция: пороги и штрафы, ни базы, ни сети. Проверка связей требует
сети (ручка на каждый адрес), и втащив её туда, мы сделали бы чистую функцию сетевой — то есть
непроверяемой без заглушек и медленной там, где она обязана быть мгновенной. Здесь своё место и
свой бюджет.

═══ ГРАНИЦА РАСХОДА ═══
Вызовов СТОЛЬКО, СКОЛЬКО АДРЕСОВ, и это единственная в дозорном проверка с такой ценой. Поэтому:
  * проверяем не больше `max_calls` адресов (по умолчанию 3) — самых крупных по объёму;
  * идём в сеть ТОЛЬКО по событию, которое уже прошло все пороги (то есть редко);
  * расход считается общей дверью `store.spend_add`, под тем же капом, что и остальной дозор;
  * не смогли проверить — ГОВОРИМ ВСЛУХ и штрафуем меньше: «связи не проверены» и «связей нет» —
    разные новости, и путать их нельзя (закон проекта: непроверенное считаем отдельной строкой,
    а не догадкой).
"""

import os

from . import store

#: Сколько адресов проверяем на связи. Ровно столько и вызовов ручки.
#: ТРИ, А НЕ ВСЕ: у зажигания адресов бывает десятки, и десять вызовов на одно событие
#: превратили бы дешёвый сигнал в дорогой. Три самых крупных покупателя отвечают на главный
#: вопрос («не один ли это человек с тремя кошельками»), потому что именно они делают объём.
MAX_CALLS = max(1, int(os.getenv('SENTINEL_CLUSTER_CALLS') or 3))

#: Цена одного вызова в кредитах. Ручка помечена в проекте как дешёвая, но точной цены источник
#: не называет — берём 1 и НЕ занижаем расход молча (закон №22: неизмеренное идёт отдельной
#: строкой, а не догадкой в свою пользу).
CREDITS_PER_CALL = max(0, int(os.getenv('SENTINEL_CLUSTER_CREDITS') or 1))


def _norm(a):
    return str(a or '').strip().lower()


def link_map(rows_by_addr):
    """Кто с кем связан ВНУТРИ нашего набора. -> {адрес: {связанные из набора}}.

    ЧИСТАЯ ФУНКЦИЯ, И ЭТО НАРОЧНО: разбор ответа отделён от сети, поэтому проверяется на
    фикстуре настоящего ответа, а не на заглушке вместо разбора.

    СЧИТАЕМ ТОЛЬКО СВЯЗИ ВНУТРИ НАБОРА. У любого живого адреса найдутся десятки связанных
    кошельков — биржи, роутеры, случайные контрагенты. Нас интересует ровно одно: не связаны ли
    между собой ТЕ, КОГО МЫ ПОСЧИТАЛИ ЗА РАЗНЫХ УЧАСТНИКОВ. Всё остальное — шум чужого графа.
    СВЯЗЬ СИММЕТРИЧНА: площадка может назвать B в ответе про A и не назвать A в ответе про B
    (мы вообще спрашиваем не про всех). Односторонняя запись дала бы разный ответ в зависимости
    от того, чей ответ пришёл первым.
    """
    ours = {_norm(a) for a in rows_by_addr if _norm(a)}
    out = {a: set() for a in ours}
    for addr, rows in (rows_by_addr or {}).items():
        a = _norm(addr)
        if a not in ours:
            continue
        for r in rows or []:
            b = _norm((r or {}).get('address') or (r or {}).get('related_address'))
            if b and b != a and b in ours:
                out[a].add(b)
                out[b].add(a)
    return out


def components(links):
    """Связные группы. -> [set]. Адрес без связей — группа из одного.

    ГРУППА, А НЕ ПАРА: если A связан с B, а B с C, то участник ОДИН, даже если A и C друг о
    друге не знают. Считая парами, мы получили бы «две связи» там, где один человек с тремя
    кошельками, и штраф оказался бы меньше правды.
    """
    seen, out = set(), []
    for a in sorted(links):
        if a in seen:
            continue
        stack, comp = [a], set()
        while stack:
            x = stack.pop()
            if x in comp:
                continue
            comp.add(x)
            stack += [y for y in links.get(x, ()) if y not in comp]
        seen |= comp
        out.append(comp)
    return out


def verdict(links, wallets_total, checked, refused=None):
    """Пересчёт числа независимых участников. -> dict.

    `independent` — СКОЛЬКО ЛЮДЕЙ, А НЕ СКОЛЬКО АДРЕСОВ. Из проверенных адресов группы
    сливаются в одного участника; непроверенные остаются каждый сам за себя — занижать их
    нельзя, про них мы ничего не знаем.
    """
    comps = components(links)
    merged = sum(len(c) - 1 for c in comps if len(c) > 1)
    groups = [sorted(c) for c in comps if len(c) > 1]
    return {'wallets': int(wallets_total), 'checked': int(checked),
            'merged': merged, 'groups': groups,
            'independent': max(1, int(wallets_total) - merged),
            'refused': refused}


def penalty(res):
    """Штраф к уверенности по вердикту. -> (текст, вес) | None. ЧИСТАЯ ФУНКЦИЯ.

    ВЕС РАСТЁТ С ДОЛЕЙ СЛИПШИХСЯ, а не стоит константой: «2 из 12 адресов связаны» и «4 из 5
    связаны» — разные новости, и один штраф на оба случая был бы неинформативен в обе стороны.
    """
    if not res:
        return None
    if res.get('refused'):
        # НЕПРОВЕРЕННОЕ - ОТДЕЛЬНАЯ СТРОКА, А НЕ МОЛЧАНИЕ И НЕ ДОГАДКА. Вес маленький: мы не
        # нашли связей, мы не СМОГЛИ их искать, и наказывать сигнал за нашу же неудачу нечестно.
        return ('связи адресов не проверены: %s' % res['refused'], 10)
    if not res.get('merged'):
        return None
    n, ind = int(res.get('wallets') or 0), int(res.get('independent') or 0)
    share = (n - ind) / float(n) if n else 0.0
    w = int(round(20 + 40 * min(1.0, share)))
    return ('из %d адресов независимых участников %d: %s связаны между собой'
            % (n, ind, ' и '.join('+'.join(g[:2]) + ('…' if len(g) > 2 else '')
                                  for g in (res.get('groups') or [])[:2])), w)


async def check(addresses, chain, max_calls=None, spend=True):
    """Проверить связи между адресами зажигания. -> dict (см. `verdict`).

    НИКОГДА НЕ БРОСАЕТ: это обогащение уверенности, и его отказ не имеет права уронить событие,
    которое уже честно посчитано по порогам. Отказ едет полем `refused` и превращается в
    маленький штраф со словами.
    """
    addrs = [_norm(a) for a in (addresses or ()) if _norm(a)]
    if len(addrs) < 2:
        # ОДИН АДРЕС НЕ С ЧЕМ СВЯЗЫВАТЬ, и это не отказ, а отсутствие вопроса.
        return verdict({}, len(addrs), 0)
    lim = max(1, int(max_calls if max_calls is not None else MAX_CALLS))
    todo = addrs[:lim]
    # ═══ КАП ПРОВЕРЯЕМ ДО ПЕРВОГО ВЫЗОВА, А НЕ ПОСЛЕ ═══
    # Спросив сначала и заплатив потом, мы бы однажды перешли кап на середине набора и получили
    # половину графа, приняв её за целый: «проверено 1 из 3» и «связей нет» выглядели бы
    # одинаково. Одна дверь бюджета на весь дозор (`store.budget_block`).
    blocked = store.budget_block()
    if spend and blocked:
        return verdict({}, len(addrs), 0, refused=blocked)
    rows_by_addr, got = {}, 0
    try:
        import asyncio

        import nansen_api as _n
        import nansen_log as _tele
        with _tele.scene('sentinel_ignition', None, surface='sentinel'):
            for a in todo:
                rows = await asyncio.to_thread(_n.profiler_related_wallets, a, chain, 10)
                got += 1
                rows_by_addr[a] = rows or []
            if spend and got:
                store.spend_add(credits=got * CREDITS_PER_CALL)
            if not any(rows_by_addr.values()):
                # ПУСТО ПО ВСЕМ АДРЕСАМ - ЭТО ПОДОЗРИТЕЛЬНО, А НЕ «СВЯЗЕЙ НЕТ». Причину берём
                # из коробки вызова, пока она ОТКРЫТА (эту ошибку мы уже совершили в lab.py:
                # читали причину после выхода из `with` и получали пустую коробку).
                _why = _n.fail_reason('empty')
                if _why != 'empty':
                    return verdict({}, len(addrs), 0, refused=_why)
    except Exception as e:                       # noqa: BLE001
        return verdict({}, len(addrs), got,
                       refused='%s: %s' % (type(e).__name__, str(e)[:90]))
    res = verdict(link_map(rows_by_addr), len(addrs), got)
    if got < len(addrs):
        # ПРОВЕРИЛИ НЕ ВСЕХ - ГОВОРИМ ЧИСЛОМ. Иначе «связей не найдено» звучало бы как вывод
        # про весь набор, хотя мы смотрели только три адреса из двенадцати.
        res['partial'] = '%d из %d адресов' % (got, len(addrs))
    return res
